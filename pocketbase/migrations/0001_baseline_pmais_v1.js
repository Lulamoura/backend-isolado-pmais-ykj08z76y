function fieldFromDefinition(definition) {
  if (definition.type === 'relation') return new RelationField(definition)
  if (definition.type === 'bool') return new BoolField(definition)
  throw new Error('Tipo de campo de usuário não suportado na baseline: ' + definition.type)
}

migrate(
  (app) => {
    for (const definition of BASELINE_COLLECTIONS) {
      try {
        app.findCollectionByNameOrId(definition.name)
        throw new Error('A baseline exige backend vazio; coleção já existe: ' + definition.name)
      } catch (error) {
        if (String((error && error.message) || error).includes('baseline exige backend vazio'))
          throw error
      }
      app.save(new Collection(definition))
    }

    const users = app.findCollectionByNameOrId('users')
    for (const definition of USER_EXTENSION_FIELDS) {
      if (users.fields.getByName(definition.name)) {
        throw new Error('A baseline exige users sem extensões; campo já existe: ' + definition.name)
      }
      users.fields.add(fieldFromDefinition(definition))
    }
    Object.assign(users, USER_RULES)
    app.save(users)

    for (const [collectionName, items] of Object.entries(STRUCTURAL_SEEDS)) {
      const collection = app.findCollectionByNameOrId(collectionName)
      for (const item of items) {
        const record = new Record(collection)
        for (const [key, value] of Object.entries(item)) record.set(key, value)
        app.save(record)
      }
    }
  },
  (app) => {
    try {
      const users = app.findCollectionByNameOrId('users')
      for (const definition of USER_EXTENSION_FIELDS) {
        if (users.fields.getByName(definition.name)) users.fields.removeByName(definition.name)
      }
      users.listRule = 'id = @request.auth.id'
      users.viewRule = 'id = @request.auth.id'
      users.createRule = ''
      users.updateRule = 'id = @request.auth.id'
      users.deleteRule = 'id = @request.auth.id'
      app.save(users)
    } catch (_) {}

    for (const definition of [...BASELINE_COLLECTIONS].reverse()) {
      try {
        app.delete(app.findCollectionByNameOrId(definition.name))
      } catch (_) {}
    }
  },
)
